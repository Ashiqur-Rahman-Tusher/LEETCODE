#include<iostream>
#include<vector>
#include<algorithm>

using namespace std;

double totalcost(vector<double> &price,int n,int k){
    if(n==0 && k==0){
        return 0;
    }

    sort(price.begin(),price.end(),greater<double>());
    double totalprice = 0;

    for(int i=0;i<n;i++){
        if(i<k){
            totalprice += price[i]*0.7;
        }
        else{
            totalprice += price[i];
        }
    }
    return totalprice;
}

int main(){

    int n = 5;
    int k = 2;
   

    vector<double> price = {20.50 , 50.00 , 30.75 , 10.20 , 60.30};

    cout<<totalcost(price,n,k)<<endl;




    return 0;
}
